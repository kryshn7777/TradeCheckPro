/* ABYSSAL TETHER 3D — pwaBoot.js
 * Service worker registration, update flow and persistent storage for the installed PWA
 * (adopted from docs/abyssal-tether-3d/pwa/pwa-boot.draft.js; design: RELEASE.md §9).
 *
 * URLs are resolved against THIS module (import.meta.url), so the same build works at the host root
 * ("/"), at a sub-path ("/TradeCheckPro/abyssal-tether-3d/") and under "/play/" or "/beta/" without edits.
 *
 * When does the service worker register?
 *   release channel (BUILD.channel === 'release')  always
 *   dev channel on a real host (GitHub Pages beta)  always
 *   dev channel on localhost / 127.0.0.1 / ::1      only with ?sw=1 (a stale worker must never serve old code to a
 *                                                    developer; the precache list is regenerated by `npm run build`)
 *   ?sw=0 anywhere                                  never; also unregisters an existing worker and clears our caches
 *
 * Update flow (safe by construction, see sw.js): a new build downloads in the background into its own cache,
 * every file checked against its SHA-256 (a half-finished deploy fails the install and the player stays on the
 * build that works). When it is ready `updates.ready` becomes true and bus 'app:update-ready' fires; the new
 * build then starts on the next cold launch, or immediately via `updates.apply()`. apply() reloads the page,
 * which ends an XR session: call it from the main menu only (it refuses while an XR session is active).
 */
import { BUILD } from './buildInfo.js';
export { detectLaunchMode } from './earlyXR.js';

const SW_URL = new URL('../../sw.js', import.meta.url).href;
const SCOPE_URL = new URL('../../', import.meta.url).href;
const UPDATE_CHECK_MS = 30 * 60 * 1000; // an installed app can stay open for hours (Quest suspends, never closes)

function isLocalHost(host) {
  return host === 'localhost' || host === '127.0.0.1' || host === '[::1]' || host === '::1' || host.endsWith('.localhost');
}

/** Whether to register the worker on this page: 'yes' | 'no' | 'purge'. */
export function serviceWorkerPolicy(win = typeof window !== 'undefined' ? window : null, build = BUILD) {
  if (!win || !win.navigator || !('serviceWorker' in win.navigator)) return 'no';
  let flag = null;
  try {
    flag = new URLSearchParams(win.location.search).get('sw');
  } catch {
    /* ignore */
  }
  if (flag === '0') return 'purge';
  if (flag === '1') return 'yes';
  if (build && build.channel !== 'release' && isLocalHost(win.location.hostname || '')) return 'no';
  return 'yes';
}

/** The Digital Goods API only exists in the Store-installed PWA (Meta's own pipeline uses it as the signal). */
export function isStoreInstall() {
  return typeof window !== 'undefined' && 'getDigitalGoodsService' in window;
}

/**
 * Registers sw.js. Resolves to an `updates` controller (never rejects):
 *   { supported, registered, ready, version, apply(), check(), onReady(fn), registration }
 * `ready` becomes true when a new build is installed and waiting; `apply()` activates it and reloads once it
 * controls the page (returns false when nothing is waiting or an XR session is running).
 */
export async function registerServiceWorker({ onUpdateReady = null, isXRActive = () => false, win = typeof window !== 'undefined' ? window : null } = {}) {
  const listeners = [];
  const updates = {
    supported: false,
    registered: false,
    ready: false,
    registration: null,
    policy: serviceWorkerPolicy(win),
    onReady(fn) {
      if (typeof fn !== 'function') return;
      listeners.push(fn);
      if (updates.ready) fn(updates);
    },
    apply() {
      const reg = updates.registration;
      if (!reg || !reg.waiting || isXRActive()) return false;
      return applyUpdateNow(reg);
    },
    check() {
      const reg = updates.registration;
      return reg ? reg.update().then(() => true, () => false) : Promise.resolve(false);
    },
  };
  if (onUpdateReady) listeners.push(onUpdateReady);

  if (updates.policy === 'purge') {
    await purgeServiceWorkers();
    return updates;
  }
  if (updates.policy !== 'yes') return updates;
  updates.supported = true;

  let reg;
  try {
    // updateViaCache 'none': the browser always revalidates sw.js itself (pairs with the no-cache header).
    reg = await navigator.serviceWorker.register(SW_URL, { scope: SCOPE_URL, type: 'classic', updateViaCache: 'none' });
  } catch {
    return updates; // the game works without it (online only)
  }
  updates.registered = true;
  updates.registration = reg;

  const notify = () => {
    // Only an update (there is a controller already); the very first install just becomes the offline copy.
    if (reg.waiting && navigator.serviceWorker.controller && !updates.ready) {
      updates.ready = true;
      for (const fn of listeners.slice()) {
        try {
          fn(updates);
        } catch {
          /* a listener must not break the others */
        }
      }
    }
  };
  notify();
  reg.addEventListener('updatefound', () => {
    const sw = reg.installing;
    if (!sw) return;
    sw.addEventListener('statechange', () => {
      if (sw.state === 'installed') notify();
    });
  });

  // Long-lived sessions: look for a new build now and then and whenever the app comes back to the foreground.
  const check = () => {
    if (typeof document !== 'undefined' && document.hidden) return;
    reg.update().catch(() => {});
  };
  if (win) {
    setInterval(check, UPDATE_CHECK_MS);
    document.addEventListener('visibilitychange', () => {
      if (!document.hidden) check();
    });
  }
  return updates;
}

/** Activates the waiting worker and reloads once it controls the page. */
export function applyUpdateNow(reg) {
  if (!reg || !reg.waiting) return false;
  let reloaded = false;
  navigator.serviceWorker.addEventListener('controllerchange', () => {
    if (reloaded) return;
    reloaded = true;
    window.location.reload();
  });
  reg.waiting.postMessage({ type: 'SKIP_WAITING' });
  return true;
}

/** ?sw=0: remove every worker in scope and our caches (support tool / escape hatch). */
export async function purgeServiceWorkers() {
  try {
    const regs = await navigator.serviceWorker.getRegistrations();
    await Promise.all(regs.filter((r) => r.scope === SCOPE_URL).map((r) => r.unregister()));
    if (typeof caches !== 'undefined') {
      const prefix = `at3d${new URL(SCOPE_URL).pathname}:`;
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith(prefix)).map((n) => caches.delete(n)));
    }
    return true;
  } catch {
    return false;
  }
}

/** Asks the browser not to evict our caches/storage under pressure (VRC.Quest.Functional.4). */
export async function requestPersistentStorage() {
  try {
    if (!navigator.storage || typeof navigator.storage.persist !== 'function') return false;
    if (await navigator.storage.persisted()) return true;
    return await navigator.storage.persist();
  } catch {
    return false;
  }
}

/** { usageMB, quotaMB, persisted } for the debug overlay / support screen. */
export async function storageReport() {
  try {
    const est = navigator.storage && navigator.storage.estimate ? await navigator.storage.estimate() : {};
    const persisted = navigator.storage && navigator.storage.persisted ? await navigator.storage.persisted() : false;
    const mb = (b) => (typeof b === 'number' ? Math.round((b / 1048576) * 10) / 10 : null);
    return { usageMB: mb(est.usage), quotaMB: mb(est.quota), persisted };
  } catch {
    return { usageMB: null, quotaMB: null, persisted: false };
  }
}

/** Build version reported by the active service worker (Settings > About). */
export function serviceWorkerVersion(timeoutMs = 1500) {
  return new Promise((resolve) => {
    const ctl = typeof navigator !== 'undefined' && navigator.serviceWorker ? navigator.serviceWorker.controller : null;
    if (!ctl) return resolve(null);
    const ch = new MessageChannel();
    const timer = setTimeout(() => resolve(null), timeoutMs);
    ch.port1.onmessage = (e) => {
      clearTimeout(timer);
      resolve(e.data && e.data.version ? e.data.version : null);
    };
    ctl.postMessage({ type: 'GET_VERSION' }, [ch.port2]);
  });
}

/** Prefetches lazy-tier files (e.g. chapter packs once the full game is owned). */
export function warmChapterPack(urls, timeoutMs = 120000) {
  return new Promise((resolve) => {
    const ctl = typeof navigator !== 'undefined' && navigator.serviceWorker ? navigator.serviceWorker.controller : null;
    if (!ctl || !Array.isArray(urls) || !urls.length) return resolve({ warmed: 0 });
    const ch = new MessageChannel();
    const timer = setTimeout(() => resolve({ warmed: 0, timeout: true }), timeoutMs);
    ch.port1.onmessage = (e) => {
      clearTimeout(timer);
      resolve(e.data || { warmed: 0 });
    };
    ctl.postMessage({ type: 'WARM', urls }, [ch.port2]);
  });
}

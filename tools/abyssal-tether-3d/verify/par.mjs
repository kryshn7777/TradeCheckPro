// Par times per section (LEVEL_FUN_PLAN item 12): src/data/par-3d.js is GENERATED from a verify report, never hand-edited.
// Par = the bot's MAIN line of each section (routes.mjs ROUTES[<section id>]) played from that section's checkpoint, per
// difficulty (report.sections_<variant>[<section id>].time). Medals (src/sim/splits3d.js): gold <= 1.0 x par, silver 1.4 x,
// brass 2.0 x. Written by `npm run verify:at3d -- --write-par`, or from a saved report:
//   node tools/abyssal-tether-3d/verify/par.mjs <verify-ch1.json> [out.js]
import fs from 'node:fs';
import path from 'node:path';
import { isMain } from './args.mjs';
import { SRC_DIR } from './root.mjs';

export const PAR_FILE = path.join(SRC_DIR, 'data', 'par-3d.js');
const VARIANTS = ['normal', 'nightmare', 'abyss'];

/** { normal: { s1: 7.4, … }, nightmare: {…}, abyss: {…} } from a verify report; null when a variant / section is missing. */
export function parFromReport(report, sectionIds) {
  const out = {};
  for (const v of VARIANTS) {
    const rows = report[`sections_${v}`];
    if (!rows) return null;
    out[v] = {};
    for (const id of sectionIds) {
      const r = rows[id];
      if (!r || !r.ok || !(r.time > 0)) return null;
      out[v][id] = r.time;
    }
  }
  return out;
}

export function parSource(par, note) {
  const lines = [
    '/* ABYSSAL TETHER 3D — par-3d.js (GENERATED by tools/abyssal-tether-3d/verify/par.mjs; do not edit by hand)',
    ' * Par seconds per section and difficulty: the bot\'s main line of the section from its checkpoint (LEVEL_FUN_PLAN item 12).',
    ' * Medals: src/sim/splits3d.js (gold <= 1.0 x par, silver 1.4 x, brass 2.0 x). Sandbox has no par.',
    ` * ${note}`,
    ' */',
    'export const PAR_3D = {',
  ];
  for (const v of VARIANTS) lines.push(`  ${v}: { ${Object.entries(par[v]).map(([k, t]) => `${k}: ${t}`).join(', ')} },`);
  lines.push('};', '');
  return lines.join('\n');
}

/** Writes the par file from a report; returns the par table (or null when the report lacks a section run). */
export function writePar(report, sectionIds, file = PAR_FILE) {
  const par = parFromReport(report, sectionIds);
  if (!par) return null;
  fs.writeFileSync(file, parSource(par, `From the verify run of ${(report.meta && report.meta.date) || 'unknown date'}.`));
  return par;
}

if (isMain(import.meta.url)) {
  const [inFile, outFile] = process.argv.slice(2);
  const report = JSON.parse(fs.readFileSync(inFile, 'utf8'));
  const ids = Object.keys(report.sections_normal || {}).filter((k) => /^s\d+$/.test(k));
  const par = writePar(report, ids, outFile || PAR_FILE);
  console.log(par ? `par written: ${outFile || PAR_FILE}` : 'report lacks a section run: nothing written');
  process.exitCode = par ? 0 : 1;
}
